    def _alembic(self, project: Path, env: dict, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run(["uv", "run", "--group", "dev", "alembic", *args], cwd=project, env=dict(os.environ, **env), capture_output=True, text=True)

    def test_migration_refuses_a_role_that_bypasses_rls_and_a_missing_role(self) -> None:
        target, owner_url, _app_url = self._generate("bypass", "tenant_projects_bypass")
        spec = design.load_spec(str(TENANT_PROJECTS))
        design.generate(spec, design.build(spec, design.recommend(spec)), str(target), tool_version=TOOL_VERSION)
        base = {"TENANT_PROJECTS_MIGRATIONS_DATABASE_URL": owner_url, **_uv_env()}
        for role, fragment in (("fa_bypass", "would bypass row-level security"), ("fa_missing", "does not exist")):
            proc = self._alembic(target, {**base, "TENANT_PROJECTS_APP_ROLE": role}, "upgrade", "head")
            self.assertNotEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertIn(fragment, proc.stdout + proc.stderr)
            tables = self.cluster.psql("SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public' AND table_name <> 'alembic_version'", db="tenant_projects_bypass")
            self.assertEqual(tables, "0", "the refused migration must leave no table behind (transactional DDL)")
            version = self.cluster.psql("SELECT count(*) FROM alembic_version", db="tenant_projects_bypass") if "alembic_version" in self.cluster.psql("SELECT string_agg(table_name, ',') FROM information_schema.tables WHERE table_schema = 'public'", db="tenant_projects_bypass") else "0"
            self.assertEqual(version, "0")
        proc = self._alembic(target, {**base, "TENANT_PROJECTS_APP_ROLE": APP_ROLE}, "upgrade", "head")
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertEqual(self.cluster.psql("SELECT count(*) FROM pg_policies WHERE tablename IN ('projects', 'tasks')", db="tenant_projects_bypass"), "2")
        self.assertEqual(self.cluster.psql("SELECT bool_and(relrowsecurity AND relforcerowsecurity) FROM pg_class WHERE relname IN ('projects', 'tasks')", db="tenant_projects_bypass"), "t")

