"""Opt-in: a generated PostgreSQL backend verified against a real, throwaway PostgreSQL through the v1.9 trust model.

Enable with ``FA_DESIGN_PG=1``; needs the PostgreSQL binaries (``initdb``, ``pg_ctl``, ``psql``) and ``uv`` (the
generated project is synced from the local uv cache into a virtual environment inside the workspace copy). Nothing
is executed outside the trust model: the generated tests run through ``LocalProcessExecutor`` (process hygiene, not
a sandbox: no network or filesystem isolation) in a copy of the generated project, with the pytest JUnit adapter
binding the report to the run. The cluster is created in a temporary directory and deleted afterwards.

What the run demonstrates (asserted here, implemented by the generated suite itself):

1. the database is empty before the suite (the generated conftest refuses a non-empty database);
2. migrations are applied with ``alembic upgrade head``;
3. tables, primary keys, unique ``(tenant_id, id)`` constraints and composite foreign keys exist;
4. rows are inserted and read through the API;
5. a request that violates referential integrity is answered 409 and leaves no row (rollback);
6. referential integrity across tenants: a foreign key can only point at a row of the same tenant;
7. ``downgrade base`` + ``upgrade head`` is repeatable and ``alembic current`` shows the generated revision;
8. unexpected schema changes are detected: ``compare_metadata`` is empty for the generated models, and a mutated
   model (negative control) makes that test fail.
"""

