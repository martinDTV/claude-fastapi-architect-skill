"""v2.0.0 acceptance: the whole engineering cycle on the plugin's own fixtures, in one reproducible scenario each.

Requirements -> architecture -> generation -> audit -> tests -> evolution -> new migration -> verification, with the
identity, authorization and tenant-isolation guarantees checked before and after the evolution. The in-memory scenario
(team-notes: OIDC, tenant from a verified claim, roles and ownership) runs wherever the generated dependencies import;
the PostgreSQL scenario (tenant-projects: API-key grants, roles and ownership, row-level security, Alembic) is opt-in
(``FA_DESIGN_PG=1``) and runs on a throwaway cluster as the restricted role. Nothing generated is executed outside an
explicit ``Authorization`` of the v1.9 trust model. Set ``FA_ACCEPTANCE_EVIDENCE`` to a directory to keep the reports.
"""

