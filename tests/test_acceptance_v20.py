MILESTONES = [{"name": "milestones", "description": "Milestones of a project.", "depends_on": ["projects"], "entities": [{"name": "Milestone", "owned": True, "fields": [{"name": "project_id", "type": "uuid", "references": "projects.Project"}, {"name": "title", "type": "str", "max_length": 120}, {"name": "due_on", "type": "date"}], "operations": ["create", "get", "list", "update"]}]}]


def _save(name: str, payload: dict) -> None:
    if EVIDENCE_DIR:
        Path(EVIDENCE_DIR).mkdir(parents=True, exist_ok=True)
        (Path(EVIDENCE_DIR) / name).write_text(json.dumps(payload, indent=2, sort_keys=True, default=str), encoding="utf-8")


class AcceptanceCase(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="fa-acceptance-")
        self.addCleanup(self._tmp.cleanup)
        self.tmp = Path(self._tmp.name).resolve()

    def contract(self, project: Path, modules: list, name: str = "evolve.json") -> Path:
        path = self.tmp / name
        path.write_text(json.dumps({"schema": evolution.EVOLUTION_SCHEMA, "project": {"path": str(project)}, "add_modules": modules}), encoding="utf-8")
        return path

    # --- the cycle, step by step; every step returns what the next one needs and asserts what the brief asks for -- #

    def step_requirements(self, spec_path: Path) -> design.Spec:
        spec = design.load_spec(str(spec_path))
        self.assertEqual(spec.schema, "fastapi-architect/spec/1.2")
        self.assertIsNone(design.generation_refusal(spec))
        self.assertGreater(sum(1 for how in spec.provenance.values() if how == "explicit"), 20)
        return spec

    def step_architecture(self, spec: design.Spec, expected_style: str) -> design.Recommendation:
        rec = design.recommend(spec)
        self.assertEqual(rec.style, expected_style)
        self.assertTrue(rec.rationale and rec.rejected)  # a reasoned choice, with the alternatives it rejected
        self.assertTrue(all(r["reason"] for r in rec.rejected))
        self.assertEqual(design.recommend(spec).to_dict(), rec.to_dict())  # deterministic
        return rec

    def step_generate_audit_test(self, spec_path: Path, target: Path, command: str, passthrough: tuple = ()) -> dict:
        authorization = Authorization(execution=True, trust="fixture", scope=str(target), declared_by="tests: acceptance scenario, project generated by this suite")
        policy = ExecutionPolicy(authorized=True, command=command, timeout_s=900, env_passthrough=tuple(DEFAULT_ENV_PASSTHROUGH) + passthrough)
        report = design.run_design(str(spec_path), design.DesignOptions(target=str(target), authorization=authorization, policy=policy, test_command=command))
        self.assertGreater(len(report["generation"]["written"]), 20)
        self.assertEqual(report["generation"]["conflicts"], [])
        audit = report["verification"]["audit"]
        self.assertLessEqual(set(audit["by_severity"]), {"info"}, audit["findings"])
        self.assertEqual((audit["contracts"]["authorization_unknown"], audit["contracts"]["unauthenticated_not_public"]), (0, 0), audit["contracts"])
        tests = report["verification"]["tests"]
        self.assertTrue(tests["ran"], tests)
        run = tests["run"]
        self.assertEqual(run["outcome"], "passed", (run.get("stdout_tail") or "")[-4000:] + (run.get("stderr_tail") or "")[-2000:])
        self.assertEqual((run["counts"]["failed"], run["counts"]["errors"], run["counts"]["skipped"]), (0, 0, 0), run["counts"])
        self.assertTrue(run["evidence"]["matched"] and run["evidence"]["verifiable"])
        self.assertEqual(tests["workspace"]["python_files_changed_by_the_run"], [])
        self.assertEqual(set(design.verify_manifest(str(target))["status"].values()), {"identical"})
        return report

    def step_evolve(self, project: Path, modules: list, command: str, passthrough: tuple = (), name: str = "evolve.json") -> dict:
        contract = self.contract(project, modules, name)
        plan = evolution.plan_evolution(evolution.load_evolution(str(contract)))
        self.assertEqual(plan.state, "planned", (plan.blockers, plan.conflicts))
        self.assertEqual(plan.conflicts, [])
        authorization = Authorization(execution=True, trust="fixture", scope=str(project), declared_by="tests: acceptance scenario, evolved copy")
        policy = ExecutionPolicy(authorized=True, command=command, timeout_s=900, env_passthrough=tuple(DEFAULT_ENV_PASSTHROUGH) + passthrough)
        report = evolution.run_evolution(evolution.load_evolution(str(contract)), evolution.EvolveOptions(apply=True, authorization=authorization, policy=policy, test_command=command))
        self.assertEqual(report["state"], "verified", (report["verification"] or {}).get("reasons"))
        self.assertEqual(report["applied"]["state"], "applied")
        verification = report["verification"]
        self.assertEqual(verification["routes"]["missing"], [])  # every pre-existing route kept its path and authentication
        self.assertGreater(verification["routes"]["after"], verification["routes"]["before"])
        self.assertEqual(verification["audit"]["blocking_new"], [])
        self.assertEqual(verification["protected_files"]["unexpectedly_changed"], [])
        run = verification["tests"]["run"]
        self.assertEqual(run["outcome"], "passed", (run.get("stdout_tail") or "")[-4000:])
        self.assertEqual((run["counts"]["failed"], run["counts"]["skipped"]), (0, 0))
        return report

    def step_compatibility(self, project: Path, before: dict, after: dict, modules_added: list) -> dict:
        """What stays true across the evolution: old tests still pass, the manifest tells the story, a repeat is a noop."""
        passed_before = {e.split("::")[-1] for e in before["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        passed_after = {e.split("::")[-1] for e in after["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        self.assertTrue(passed_before <= passed_after, sorted(passed_before - passed_after)[:10])  # nothing that passed stopped passing
        model = discover(str(project))  # with the audit: the route model comes from the contracts
        self.assertEqual([h["operation"] for h in model.manifest["history"]], ["generate", "evolve"])
        self.assertEqual(set(model.ownership.values()), {"managed_unchanged"})  # no file left outside the manifest, none hand-edited
        for name in modules_added:
            self.assertIn(name, model.modules)
        guarantees = design.security_guarantees(model.baseline_spec)
        security = model.manifest["security"]
        self.assertEqual(security["row_level_security"], guarantees["multi_tenant"]["row_level_security"])
        self.assertEqual(security["tenant_strategy_implemented"], guarantees["multi_tenant"]["strategy_implemented"])
        self.assertEqual(security["authorization_model"], guarantees["authorization_model"])
        return {"history": model.manifest["history"], "modules": model.modules, "routes": len(model.routes), "security": security}


@unittest.skipUnless(HAS_JWT and PY312, "fastapi, pytest, httpx, PyJWT and cryptography on Python >= 3.12 are needed by the generated suite")
class EndToEndInMemoryTests(AcceptanceCase):
    def test_requirements_to_verified_evolution_with_authorization(self) -> None:
        started = time.time()
        command = f"{sys.executable} -m pytest -q -p no:cacheprovider"
        spec = self.step_requirements(TEAM_NOTES)
        rec = self.step_architecture(spec, "layered")
        self.assertIn("one package by layer", rec.rationale[0])
        target = self.tmp / "team-notes"
        generated = self.step_generate_audit_test(TEAM_NOTES, target, command)
        passed = {e.split("::")[-1] for e in generated["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        for expected in ("test_create_note", "test_another_member_cannot_update_note_of_a_colleague", "test_an_admin_can_update_note_of_another_member", "test_create_note_needs_a_permitted_role", "test_note_of_another_tenant_is_not_found_through_the_callers_tenant", "test_a_member_of_another_tenant_is_403_not_401", "test_keys_are_fetched_over_https_and_a_valid_signature_is_accepted"):
            self.assertIn(expected, passed)
        routes_before = len(discover(str(target)).routes)
        evolved = self.step_evolve(target, BOARDS, command)
        self.assertEqual(evolved["plan"]["added_modules"], ["boards"])
        self.assertIn("src/team_notes/api/boards.py", evolved["plan"]["files"]["create"])
        self.assertNotIn("src/team_notes/core/security.py", evolved["plan"]["files"]["modify"])  # identity code untouched by an evolution
        self.assertNotIn("src/team_notes/core/authz.py", evolved["plan"]["files"]["modify"])
        passed_after = {e.split("::")[-1] for e in evolved["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        for expected in ("test_create_board", "test_another_member_cannot_update_board_of_a_colleague", "test_board_of_another_tenant_is_not_found_through_the_callers_tenant", "test_create_board_needs_a_permitted_role"):
            self.assertIn(expected, passed_after)  # the policy applies to the new owned entity with no extra declaration
        compatibility = self.step_compatibility(target, generated, evolved, ["boards"])
        self.assertEqual(compatibility["routes"], routes_before + 5)
        again = evolution.run_evolution(evolution.load_evolution(str(self.contract(target, BOARDS, "again.json"))), evolution.EvolveOptions(apply=True))
        self.assertEqual(again["state"], "noop")
        audit_after = design.audit_generated(str(target))
        self.assertEqual(audit_after["findings_total"], 0, audit_after["findings"])
        self.assertEqual(audit_after["contracts"]["authorization_unknown"], 0)
        _save("acceptance-team-notes.json", {"wall_s": round(time.time() - started, 1), "recommendation": rec.to_dict(), "generation": {k: generated[k] for k in ("guarantees", "verification")}, "evolution": {k: evolved[k] for k in ("state", "plan", "verification", "applied")}, "compatibility": compatibility, "repeat": again["state"], "audit_after": audit_after})


@unittest.skipUnless(PG_ENABLED, "set FA_DESIGN_PG=1 to run the PostgreSQL acceptance scenario on a throwaway cluster")
class EndToEndPostgresTests(AcceptanceCase):
    @classmethod
    def setUpClass(cls) -> None:
        from _pg_support import ThrowawayCluster, pg_available

        if not (pg_available() and shutil.which("uv")):
            raise unittest.SkipTest("PostgreSQL binaries and uv are required")
        cls.cluster = ThrowawayCluster().__enter__()
        cls.cluster.create_role("fa_app")

    @classmethod
    def tearDownClass(cls) -> None:
        cls.cluster.__exit__(None, None, None)

    def test_requirements_to_verified_evolution_with_rls_and_a_second_revision(self) -> None:
        from test_design_v20_postgresql import _uv_env

        started = time.time()
        owner_url = self.cluster.create_database("acceptance_tp")
        app_url = self.cluster.url_for("acceptance_tp", "fa_app")
        env = {"DATABASE_URL": app_url, "TENANT_PROJECTS_MIGRATIONS_DATABASE_URL": owner_url, "TENANT_PROJECTS_APP_ROLE": "fa_app", **_uv_env()}
        os.environ.update(env)
        passthrough = tuple(env)
        command = "uv run --group dev pytest -q -p no:cacheprovider"
        spec = self.step_requirements(TENANT_PROJECTS)
        rec = self.step_architecture(spec, "modular_monolith")
        target = self.tmp / "tenant-projects"
        generated = self.step_generate_audit_test(TENANT_PROJECTS, target, command, passthrough)
        g = generated["guarantees"]["multi_tenant"]
        self.assertTrue(g["row_level_security"])
        self.assertEqual(g["strategy_implemented"], "shared_schema_rls")
        passed = {e.split("::")[-1] for e in generated["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        for expected in ("test_migrated_schema_matches_the_models", "test_every_tenant_table_has_rls_enabled_forced_and_a_policy", "test_the_context_is_a_setting_that_any_statement_run_as_the_application_role_can_change", "test_another_member_cannot_update_task_of_a_colleague", "test_delete_task_needs_a_permitted_role", "test_create_task_cannot_reference_a_project_id_of_another_tenant"):
            self.assertIn(expected, passed)
        manifest_before = design.verify_manifest(str(target))["manifest"]
        self.assertEqual(len(manifest_before["migrations"]), 1)
        evolved = self.step_evolve(target, MILESTONES, command, passthrough)
        migration = evolved["plan"]["migration"]
        self.assertTrue(migration["required"])
        self.assertEqual(migration["tables"], ["milestones"])
        self.assertEqual(migration["head_before"], manifest_before["migrations"][0]["revision"])
        new_revision = (target / migration["file"]).read_text(encoding="utf-8")
        self.assertIn('_protect("milestones")', new_revision)
        self.assertIn('sa.Column("owner_id"', new_revision)  # the owned entity of the new module
        model = discover(str(target))
        self.assertEqual(len(model.manifest["migrations"]), 2)
        self.assertEqual(model.alembic["heads"], [migration["new_revision"]])
        self.assertTrue(model.alembic["chain_ok"])
        self.assertEqual(model.alembic["historical_modified"], [])
        passed_after = {e.split("::")[-1] for e in evolved["verification"]["tests"]["run"]["evidence"]["tests"]["passed"]}
        for expected in ("test_upgrade_and_downgrade_are_repeatable", "test_every_tenant_table_has_rls_enabled_forced_and_a_policy", "test_create_milestone", "test_another_member_cannot_update_milestone_of_a_colleague", "test_milestone_of_another_tenant_is_not_found_through_the_callers_tenant", "test_another_member_cannot_update_task_of_a_colleague"):
            self.assertIn(expected, passed_after)
        compatibility = self.step_compatibility(target, generated, evolved, ["milestones"])
        self.assertTrue(compatibility["security"]["row_level_security"])
        remaining = self.cluster.psql("SELECT string_agg(table_name, ',' ORDER BY table_name) FROM information_schema.tables WHERE table_schema = 'public'", db="acceptance_tp")
        self.assertEqual(remaining, "alembic_version")  # the evolved suite downgraded the chain at the end
        _save("acceptance-tenant-projects.json", {"wall_s": round(time.time() - started, 1), "recommendation": rec.to_dict(), "generation": {k: generated[k] for k in ("guarantees", "verification")}, "evolution": {k: evolved[k] for k in ("state", "plan", "verification", "applied")}, "compatibility": compatibility})


class ManifestAndGuaranteesConsistencyTests(unittest.TestCase):
    """The manifest's security record and the report's guarantees are two renderings of the same contract: they must agree."""

    def test_every_committed_snapshot_agrees_with_its_guarantees(self) -> None:
        for name in ("inventory-service", "orders-platform", "team-notes", "tenant-projects"):
            with self.subTest(snapshot=name):
                manifest = json.loads((EXAMPLES / "generated" / name / ".fastapi-architect" / "generation.json").read_text(encoding="utf-8"))
                spec, errors = design.validate_spec(manifest["spec_document"])
                self.assertEqual(errors, [])
                g = design.security_guarantees(spec)
                s = manifest["security"]
                self.assertEqual(s["row_level_security"], g["multi_tenant"]["row_level_security"])
                self.assertEqual(s["tenant_strategy_implemented"], g["multi_tenant"]["strategy_implemented"])
                self.assertEqual(s["authorization_model"], g["authorization_model"])
                self.assertEqual(s["authentication"], spec.security["authentication"])
                self.assertEqual(all(m.get("row_level_security") for m in manifest["migrations"]) if manifest["migrations"] else False, s["row_level_security"])
                self.assertEqual(manifest["tool"]["version"], "2.0.0")


if __name__ == "__main__":
    unittest.main()
